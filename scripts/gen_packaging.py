def _list(items, indent="    "):
    return "\n".join(f'{indent}"{item}",' for item in items)


def render(name, spec):
    module = f"flexcommerce_{name}" if name != "meta" else "flexcommerce"
    keywords = ", ".join(
        f'"{k}"' for k in ["django", "ecommerce", "flexcommerce", "nigeria", "africa", "drf", *spec.get("keywords", [])]
    )
    extras = ""
    if spec.get("extras"):
        extras = (
            "\n[project.optional-dependencies]\n"
            + "\n".join(
                f"{key} = [{', '.join(repr(v).replace(chr(39), chr(34)) for v in values)}]"
                for key, values in spec["extras"].items()
            )
            + "\n"
        )
    package_data = ""
    if spec.get("data"):
        package_data = (
            f"\n[tool.setuptools.package-data]\n{module} = [{', '.join(chr(34) + d + chr(34) for d in spec['data'])}]\n"
        )
    return TEMPLATE.format(
        dist=spec.get("dist", f"flexcommerce-{name}"),
        version=VERSION,
        description=spec["description"],
        keywords=keywords,
        classifiers=CLASSIFIERS,
        deps=_list(spec["deps"]),
        extras=extras,
        module=module,
        package_data=package_data,
    )


