def outputs():
    files = {}
    for name, spec in PACKAGES.items():
        base = ROOT / f"flexcommerce-{name}"
        files[base / "pyproject.toml"] = render(name, spec)
        files[base / "MANIFEST.in"] = MANIFEST.format(module=f"flexcommerce_{name}")
    files[ROOT / "flexcommerce-meta" / "pyproject.toml"] = render("meta", meta_spec())
    files[ROOT / "flexcommerce-meta" / "MANIFEST.in"] = MANIFEST.format(module="flexcommerce")
    return files


def main(check=False):
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if stale:
        print("Out of date:\n  " + "\n  ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main(check="--check" in sys.argv)
